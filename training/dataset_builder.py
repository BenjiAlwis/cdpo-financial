"""
training/dataset_builder.py
============================
Builds a HuggingFace Dataset from:
  1. JSONL metadata files (generated by scripts/generate_full.py)
  2. Client description JSON files (generated by GPT-4o/Claude API calls)

The resulting dataset has columns:
    prompt      : str  — full formatted prompt (system + user, chat format)
    instance_id : str  — for ScenarioStore lookup
    task        : str  — "portfolio" | "retirement" | "loan"
    difficulty  : str  — "easy" | "medium" | "hard"

The 'prompt' column uses the chat template format expected by the model
(apply_chat_template). The instance_id is embedded in the system message
via ScenarioStore.embed_id().

Usage
-----
    from training.dataset_builder import build_dataset

    ds = build_dataset(
        metadata_paths = {
            "portfolio":  "data/full/portfolio_train.jsonl",
            "retirement": "data/full/retirement_train.jsonl",
            "loan":       "data/full/loan_train.jsonl",
        },
        descriptions_paths = {
            "portfolio":  "data/full/portfolio_descriptions.json",
            "retirement": "data/full/retirement_descriptions.json",
            "loan":       "data/full/loan_descriptions.json",
        },
        tokenizer = tokenizer,   # for apply_chat_template
    )
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def _load_jsonl(path: str | Path) -> list[dict]:
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found: {path}")
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def _load_descriptions(path: str | Path) -> dict[str, str]:
    """
    Load client descriptions from a JSON file.
    Expected format:
        { "portfolio_0000": "Jordan Chen, 42, software engineer...",
          "portfolio_0001": "Maria Santos, 58, retired teacher...", ... }

    If the file doesn't exist, returns empty dict — prompts will use a
    placeholder description. This lets training run even before descriptions
    are generated.
    """
    path = Path(path) if path else None
    if path is None or str(path) in ("", ".") or not path.exists():
        logger.debug(
            "No separate descriptions file at %s; relying on inline "
            "client_description or placeholder.", path
        )
        return {}
    with open(path) as f:
        return json.load(f)


_PLACEHOLDER = (
    "A client seeking financial planning advice. "
    "Please provide a structured plan based on the constraints provided."
)


def build_dataset(
    metadata_paths:     dict[str, str | Path],
    tokenizer,
    descriptions_paths: dict[str, str | Path] | None = None,
    max_prompt_length:  int = 1024,
) -> Any:
    """
    Build a HuggingFace Dataset ready for TRL GRPOTrainer.

    Parameters
    ----------
    metadata_paths : dict mapping task name → path to <task>_train.jsonl (or
        <task>_train_with_desc.jsonl, which carries inline client_description).
    tokenizer : HuggingFace tokenizer (used for apply_chat_template)
    descriptions_paths : optional dict mapping task → separate descriptions JSON.
        Only needed if the metadata JSONL does NOT already carry an inline
        `client_description` field. Inline descriptions take precedence.
    max_prompt_length : truncate prompts longer than this (in tokens)

    Returns
    -------
    datasets.Dataset with columns: prompt, instance_id, task, difficulty
    """
    descriptions_paths = descriptions_paths or {}
    from datasets import Dataset
    from training.scenario_store import ScenarioStore
    from finplanenv.dataset import (
        DatasetConfig, DatasetGenerator, ScenarioSampler, MARKET_PARAMS,
    )
    from finplanenv.parser import SYSTEM_PROMPT

    config  = DatasetConfig()
    gen     = DatasetGenerator(config)
    sampler = ScenarioSampler(config)

    rows = []

    for task, meta_path in metadata_paths.items():
        logger.info("Building dataset for task: %s", task)
        metadata      = _load_jsonl(meta_path)
        descriptions  = _load_descriptions(descriptions_paths.get(task, ""))

        for meta in metadata:
            iid  = meta["instance_id"]
            idx  = int(iid.split("_")[1])

            # Description precedence:
            #   1. inline `client_description` field (from generate_descriptions.py
            #      writing *_with_desc.jsonl) — preferred, self-contained;
            #   2. separate descriptions JSON keyed by instance_id;
            #   3. placeholder (lets training run before descriptions exist).
            description = (
                meta.get("client_description")
                or descriptions.get(iid)
                or _PLACEHOLDER
            )

            # Build prompt using DatasetGenerator
            system_p, user_p = gen.build_training_prompt(task, meta, description)

            # Embed instance_id into system prompt for ScenarioStore lookup
            from training.scenario_store import ScenarioStore
            system_p_with_id = ScenarioStore.embed_id(system_p, iid)

            # Format as chat messages
            messages = [
                {"role": "system",    "content": system_p_with_id},
                {"role": "user",      "content": user_p},
            ]

            # Apply chat template
            prompt = tokenizer.apply_chat_template(
                messages,
                tokenize    = False,
                add_generation_prompt = True,
            )

            rows.append({
                "prompt":      prompt,
                "instance_id": iid,
                "task":        task,
                "difficulty":  meta.get("difficulty", "unknown"),
            })

    logger.info("Dataset built: %d total prompts", len(rows))
    return Dataset.from_list(rows)


def build_eval_dataset(
    metadata_paths:     dict[str, str | Path],
    descriptions_paths: dict[str, str | Path],
    tokenizer,
    split: str = "audit",   # use the 50-instance audit split
) -> Any:
    """
    Build evaluation dataset from <task>_audit.jsonl files.
    Same format as training dataset.
    """
    audit_paths = {}
    for task, path in metadata_paths.items():
        path = Path(path)
        audit_path = path.parent / path.name.replace("train", split)
        audit_paths[task] = audit_path

    return build_dataset(
        metadata_paths     = audit_paths,
        descriptions_paths = descriptions_paths,
        tokenizer          = tokenizer,
    )
