@dataclass
class DatasetConfig:
    """
    Controls dataset size, composition, and random seed.

    n_instances_per_task : total instances per task (≥500 per paper spec)
    pilot_size           : instances for pilot calibration run
    seed                 : global random seed for reproducibility
    tasks                : which tasks to generate
    n_assets_portfolio   : number of assets in portfolio task
    n_asset_classes_ret  : number of asset classes in retirement task
    """
    n_instances_per_task: int   = 550    # 500 train + 50 for manual audit
    pilot_size:           int   = 60     # 20 per difficulty tier
    seed:                 int   = 2024
    tasks:                list  = field(
        default_factory=lambda: ["portfolio", "retirement", "loan"]
    )
    n_assets_portfolio:   int   = 4
    n_asset_classes_ret:  int   = 2
    # Conflict calibration (Day-6). 0.0 = original behaviour (no engineered
    # hard/soft conflict — reproduces the null result). >0 injects tension:
    # the highest-ESG asset's sector is banned, so maximizing the ESG soft
    # preference (S2) forces a banned-sector hard-constraint violation (H3).
    # Scaled by difficulty tier when conflict_by_tier=True. This is the switch
    # that makes CDPO's gate actually matter.
    conflict_level:       float = 0.0
    conflict_by_tier:     bool  = True


