"""
finplanenv/dataset.py
=====================
Dataset generation for FinPlanEnv.

Three components:

1. ScenarioSchema     — defines every field in a client profile, its
                        type, range, and how it is sampled per difficulty tier.

2. DatasetConfig      — calibration parameters controlling the difficulty
                        distribution (easy/medium/hard mix).

3. ScenarioSampler    — samples scenario instances deterministically from
                        the schema.  Pure numpy, no external APIs.

4. GenerationPrompt   — builds the GPT-4o/Claude prompt that generates
                        diverse natural-language client descriptions to
                        accompany the structured scenario data.

5. DatasetGenerator   — orchestrates pilot → calibrate → scale workflow.

Design principles
-----------------
- Structured scenario fields (market data, constraint thresholds) are
  sampled deterministically by ScenarioSampler — no LLM needed for these.
- Natural-language client descriptions (narrative, goals, preferences) are
  generated by GPT-4o/Claude from a structured prompt, then embedded in
  the LLM training prompt as context.
- Difficulty is controlled analytically via constraint thresholds, not by
  hoping the LLM produces the right difficulty level.
- All randomness is seeded for reproducibility.

Key calibration finding (from simulation, see analysis):
  Portfolio: Dirichlet(α≈2) weights → H2 pass≈0.69, H4 pass≈0.36
             → medium CCR achievable via D*=-0.12, H*=0.25
  Retirement: WR=4% → survival≈0.86 (medium difficulty at θ=0.90)
  Loan: H1 ≈ H3 (correlation ρ≈1.0) → correlation correction fires
         → effective independent constraints = 2, not 3

Difficulty targets:
  Easy   (30%): group CCR ∈ [0.6, 1.0]
  Medium (40%): group CCR ∈ [0.2, 0.6]  ← maximum signal diversity
  Hard   (30%): group CCR ∈ [0.0, 0.2]
"""

