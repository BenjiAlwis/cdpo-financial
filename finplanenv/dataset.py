# Fixed market parameters (held constant across all scenarios)
# Using stylised facts from historical data
MARKET_PARAMS = {
    "portfolio": {
        "expected_returns": np.array([0.12, 0.09, 0.07, 0.04]),   # annual
        "volatilities":     np.array([0.22, 0.18, 0.14, 0.08]),   # annual std
        "correlations": np.array([                                   # asset corr
            [1.00, 0.45, 0.30, 0.10],
            [0.45, 1.00, 0.25, 0.15],
            [0.30, 0.25, 1.00, 0.05],
            [0.10, 0.15, 0.05, 1.00],
        ]),
        "esg_ratings":        np.array([72., 85., 60., 45.]),
        "benchmark_weights":  np.array([0.25, 0.25, 0.25, 0.25]),
        "sectors": ["technology", "financials", "energy", "utilities"],
        "tickers": ["AAPL", "JPM", "XOM", "NEE"],
        "all_sectors": [
            "technology", "financials", "energy", "utilities",
            "healthcare", "consumer_discretionary", "consumer_staples",
            "industrials", "materials", "real_estate",
        ],
    },
    "retirement": {
        "expected_returns": np.array([0.08, 0.04]),    # equities, bonds
        "cov_matrix": np.array([
            [0.0400, 0.0050],
            [0.0050, 0.0010],
        ]),
    },
}

def _build_portfolio_cov(params: dict) -> np.ndarray:
    """Build covariance matrix from volatilities and correlations."""
    vols = params["volatilities"]
    corr = params["correlations"]
    cov  = np.outer(vols, vols) * corr
    return cov


ALL_SECTORS = MARKET_PARAMS["portfolio"]["all_sectors"]

# 3yr daily return series — generated once per scenario from market params
def _sample_return_series(
    params: dict,
    rng: np.random.Generator,
    T: int = 756,  # 3 years of trading days
) -> np.ndarray:
    """Sample a realistic historical return series shape (T, N)."""
    N = len(params["expected_returns"])
    cov = _build_portfolio_cov(params)
    daily_mu  = params["expected_returns"] / 252
    daily_cov = cov / 252
    returns = rng.multivariate_normal(daily_mu, daily_cov, size=T)
    return returns


class ScenarioSampler:
    """
    Generates fully-specified scenario instances for all three tasks.

    Each instance is deterministic given (task, instance_idx, seed).
    Difficulty tier is assigned round-robin within each tier's share,
    then thresholds are sampled uniformly within the tier's range.
    """

    def __init__(self, config: DatasetConfig):
        self.config = config
        self.master_rng = np.random.default_rng(config.seed)

    def _tier_for_idx(self, idx: int, n_total: int) -> str:
        """Assign difficulty tier based on instance index."""
        # Compute cumulative shares
        shares = [t.share for t in DIFFICULTY_TIERS]
        boundaries = np.cumsum([0.0] + shares) * n_total
        for i, tier in enumerate(DIFFICULTY_TIERS):
            if idx < boundaries[i + 1]:
                return tier.name
        return DIFFICULTY_TIERS[-1].name  # fallback

    def _rng(self, idx: int) -> np.random.Generator:
        """Deterministic per-instance RNG."""
        return np.random.default_rng(self.config.seed + idx * 31337)

    # ── Portfolio scenarios ──────────────────────────────────────────────────

    def sample_portfolio(self, idx: int) -> tuple[
        PortfolioScenario, PortfolioConstraints, dict
    ]:
        """
        Returns (scenario, constraints, metadata).
        metadata contains difficulty tier and narrative hints for
        the GPT-4o description generation prompt.
        """
        rng  = self._rng(idx)
        tier = self._tier_for_idx(idx, self.config.n_instances_per_task)
        thr  = PORTFOLIO_THRESHOLDS[tier]
        params = MARKET_PARAMS["portfolio"]

        # Constraint thresholds (sampled within tier range)
        D_star = float(rng.uniform(*thr["max_drawdown_limit"]))
        H_star = float(rng.uniform(*thr["hhi_limit"]))
        n_banned = int(rng.integers(thr["n_banned_sectors"][0],
                                    thr["n_banned_sectors"][1] + 1))
        banned = set(rng.choice(ALL_SECTORS, size=n_banned, replace=False).tolist())
        # Never ban all available sectors
        banned -= set(params["sectors"])  # keep the 4 main sectors available
        banned  = set(list(banned)[:n_banned])

        # ── Conflict calibration (Day-6) ──────────────────────────────────────
        # Original behaviour bans only OFF-universe sectors, so H3 (no banned
        # sector) is trivially satisfiable while maximizing the ESG soft pref —
        # i.e. NO hard/soft conflict, which reproduces the null result.
        #
        # When conflict_level > 0 we ban the sector of the HIGHEST-ESG asset.
        # Now maximizing ESG (S2 = w·esg) pulls weight toward the banned sector,
        # directly fighting H3. The strength scales with tier so the paper gets
        # a conflict GRADIENT (easy≈none → hard=maximal), which is exactly the
        # regime where CDPO's soft-channel gate should beat GRPO/GDPO.
        cl = self.config.conflict_level
        if cl > 0.0:
            if self.config.conflict_by_tier:
                tier_scale = {"easy": 0.0, "medium": 0.5, "hard": 1.0}[tier]
            else:
                tier_scale = 1.0
            if rng.random() < cl * tier_scale:
                esg = params["esg_ratings"]
                top_esg_idx = int(np.argmax(esg))
                conflict_sector = params["sectors"][top_esg_idx]
                banned = set(banned) | {conflict_sector}

        # Return series (sampled per scenario for realistic variability)
        return_series = _sample_return_series(params, rng)

        # Client narrative hints
        risk_tolerance = rng.choice(["conservative", "moderate", "aggressive"])
        esg_priority   = rng.choice(["low", "medium", "high"])
        time_horizon   = int(rng.integers(3, 20))  # years
        portfolio_size = float(rng.uniform(100_000, 5_000_000))

        scenario = PortfolioScenario(
            n_assets          = self.config.n_assets_portfolio,
            expected_returns  = params["expected_returns"],
            cov_matrix        = _build_portfolio_cov(params),
            esg_ratings       = params["esg_ratings"],
            benchmark_weights = params["benchmark_weights"],
            return_series     = return_series,
            banned_sectors    = banned,
        )
        constraints = PortfolioConstraints(
            weight_sum_tol       = 0.01,
            max_drawdown_limit   = D_star,
            banned_sectors       = banned,
            hhi_limit            = H_star,
            risk_free_rate       = 0.04,
        )
        metadata = {
            "instance_id":    f"portfolio_{idx:04d}",
            "difficulty":     tier,
            "max_drawdown_limit": D_star,
            "hhi_limit":          H_star,
            "banned_sectors":     list(banned),
            "narrative_hints": {
                "risk_tolerance":  str(risk_tolerance),
                "esg_priority":    str(esg_priority),
                "time_horizon_yr": time_horizon,
                "portfolio_size":  portfolio_size,
            },
        }
        return scenario, constraints, metadata

    # ── Retirement scenarios ─────────────────────────────────────────────────

    def sample_retirement(self, idx: int) -> tuple[
        RetirementScenario, RetirementConstraints, dict
    ]:
        rng  = self._rng(idx + 100_000)   # offset to avoid overlap with portfolio
        tier = self._tier_for_idx(idx, self.config.n_instances_per_task)
        thr  = RETIREMENT_THRESHOLDS[tier]
        params = MARKET_PARAMS["retirement"]

        # Client demographics
        current_age = int(rng.integers(55, 71))
        target_age  = int(rng.integers(88, 101))
        # Wealth: correlated with age (older → more accumulated)
        wealth_base = float(rng.uniform(200_000, 3_000_000))

        # Constraint thresholds
        theta_mc    = float(rng.uniform(*thr["mc_survival_threshold"]))
        floor_mo    = float(rng.uniform(*thr["income_floor_monthly"]))

        # Implied withdrawal rate hint (included in narrative, not enforced)
        wr_hint = float(rng.uniform(*thr["withdrawal_rate_hint"]))

        # Lifestyle markers
        lifestyle    = rng.choice(["frugal", "moderate", "comfortable", "lavish"])
        has_pension  = bool(rng.random() > 0.6)
        spouse       = bool(rng.random() > 0.5)
        bequest_pref = rng.choice(["none", "modest", "substantial"])

        scenario = RetirementScenario(
            initial_balance      = wealth_base,
            current_age          = current_age,
            target_age           = target_age,
            n_assets             = self.config.n_asset_classes_ret,
            expected_returns     = params["expected_returns"],
            cov_matrix           = params["cov_matrix"],
            income_floor_monthly = floor_mo,
        )
        constraints = RetirementConstraints(
            mc_survival_threshold = theta_mc,
            income_floor_monthly  = floor_mo,
            n_mc                  = 1000,
            mc_seed               = self.config.seed + idx,
        )
        metadata = {
            "instance_id":    f"retirement_{idx:04d}",
            "difficulty":     tier,
            "mc_threshold":   theta_mc,
            "income_floor":   floor_mo,
            "narrative_hints": {
                "current_age":    current_age,
                "target_age":     target_age,
                "initial_balance":wealth_base,
                "lifestyle":      str(lifestyle),
                "has_pension":    has_pension,
                "spouse":         spouse,
                "bequest_pref":   str(bequest_pref),
                "wr_hint_pct":    round(wr_hint * 100, 1),
            },
        }
        return scenario, constraints, metadata

    # ── Loan scenarios ───────────────────────────────────────────────────────

    def sample_loan(self, idx: int) -> tuple[
        LoanScenario, LoanConstraints, dict
    ]:
        rng  = self._rng(idx + 200_000)
        tier = self._tier_for_idx(idx, self.config.n_instances_per_task)
        thr  = LOAN_THRESHOLDS[tier]

        # Constraint thresholds
        dti_limit = float(rng.uniform(*thr["dti_limit"]))
        ltv_limit = float(rng.uniform(*thr["ltv_limit"]))

        # Client financials (sampled consistently)
        annual_income    = float(rng.uniform(36_000, 300_000))
        monthly_income   = annual_income / 12.0
        pti_ratio        = float(rng.uniform(
            thr["prop_to_income_ratio"][0],
            thr["prop_to_income_ratio"][1]
        ))
        property_value   = annual_income * pti_ratio

        # Client narrative hints
        credit_score   = int(rng.integers(580, 820))
        employment     = rng.choice(["salaried", "self_employed", "contractor"])
        loan_purpose   = rng.choice(["purchase", "refinance", "investment"])
        reg_tier       = "QM" if credit_score >= 620 else "non-QM"
        existing_debts = float(rng.uniform(0, 0.12 * monthly_income))

        scenario = LoanScenario(
            property_value       = property_value,
            gross_monthly_income = monthly_income,
        )
        constraints = LoanConstraints(
            dti_limit       = dti_limit,
            ltv_limit       = ltv_limit,
            rate_benchmark  = 0.12,
        )
        metadata = {
            "instance_id":    f"loan_{idx:04d}",
            "difficulty":     tier,
            "dti_limit":      dti_limit,
            "ltv_limit":      ltv_limit,
            "narrative_hints": {
                "annual_income":   annual_income,
                "property_value":  property_value,
                "credit_score":    credit_score,
                "employment":      str(employment),
                "loan_purpose":    str(loan_purpose),
                "regulatory_tier": reg_tier,
                "existing_debts_monthly": existing_debts,
            },
        }
        return scenario, constraints, metadata

    # ── Unified sampler ──────────────────────────────────────────────────────

    def sample(self, task: str, idx: int):
        """Sample one instance for any task."""
        if task == "portfolio":
            return self.sample_portfolio(idx)
        elif task == "retirement":
            return self.sample_retirement(idx)
        elif task == "loan":
            return self.sample_loan(idx)
        else:
            raise ValueError(f"Unknown task: {task!r}")


