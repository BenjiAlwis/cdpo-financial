# ──────────────────────────────────────────────────────────────────────────────
#  5. DatasetGenerator — pilot → calibrate → scale workflow
# ──────────────────────────────────────────────────────────────────────────────

class DatasetGenerator:
    """
    Orchestrates the full dataset generation workflow.

    Workflow
    --------
    1. generate_pilot(task)  — generate config.pilot_size instances
    2. calibrate(task, pilot_rewards)  — check CCR distribution,
       flag if calibration is off, suggest threshold adjustments
    3. generate_full(task)   — generate config.n_instances_per_task instances
    4. save(path)            — serialise dataset to JSONL

    The scenario and constraints objects are not directly serialisable
    (they contain numpy arrays), so save() stores the metadata dicts
    and the sampler re-creates scenarios on the fly during training.
    """

    def __init__(self, config: DatasetConfig):
        self.config  = config
        self.sampler = ScenarioSampler(config)

    def generate_instances(
        self,
        task:  str,
        start: int,
        end:   int,
    ) -> list[dict]:
        """
        Generate instances [start, end) for task.
        Returns list of metadata dicts (serialisable).
        """
        instances = []
        for idx in range(start, end):
            _, _, metadata = self.sampler.sample(task, idx)
            instances.append(metadata)
        return instances

    def calibration_report(
        self,
        task:   str,
        ccr_values: list[float],
    ) -> dict:
        """
        Given observed CCR values from a pilot run, report whether the
        difficulty distribution matches targets and suggest adjustments.

        Parameters
        ----------
        task       : task name
        ccr_values : list of observed group CCRs from pilot (one per instance)

        Returns
        -------
        dict with keys: status, tier_fractions, recommendations
        """
        ccr = np.array(ccr_values)
        easy_frac   = float((ccr >= 0.6).mean())
        medium_frac = float(((ccr >= 0.2) & (ccr < 0.6)).mean())
        hard_frac   = float((ccr < 0.2).mean())

        targets = {
            "easy": 0.30, "medium": 0.40, "hard": 0.30
        }
        observed = {
            "easy": easy_frac, "medium": medium_frac, "hard": hard_frac
        }

        recommendations = []
        thr_map = {
            "portfolio":  PORTFOLIO_THRESHOLDS,
            "retirement": RETIREMENT_THRESHOLDS,
            "loan":       LOAN_THRESHOLDS,
        }[task]

        if easy_frac > 0.45:  # too many easy instances
            recommendations.append(
                "Too many easy instances (CCR > 0.6). "
                "Tighten hard-tier constraint thresholds: "
                f"e.g. reduce max_drawdown_limit or hhi_limit for {task}."
            )
        if hard_frac > 0.45:  # too many hard instances
            recommendations.append(
                "Too many hard instances (CCR < 0.2). "
                "Loosen easy-tier constraint thresholds or "
                "shift difficulty tier boundaries."
            )
        if medium_frac < 0.25:  # too few medium instances — worst case
            recommendations.append(
                "CRITICAL: Too few medium instances (CCR 0.2–0.6). "
                "Medium instances produce maximum signal diversity. "
                "Adjust tier boundaries or threshold ranges."
            )

        status = "OK" if not recommendations else "NEEDS_CALIBRATION"

        return {
            "task":            task,
            "n_pilot":         len(ccr_values),
            "mean_ccr":        float(ccr.mean()),
            "std_ccr":         float(ccr.std()),
            "tier_fractions":  observed,
            "tier_targets":    targets,
            "status":          status,
            "recommendations": recommendations,
        }

    def build_training_prompt(
        self,
        task:     str,
        metadata: dict,
        client_description: str,
    ) -> tuple[str, str]:
        """
        Build the (system_prompt, user_prompt) pair for RL training.

        Parameters
        ----------
        task               : task name
        metadata           : instance metadata from sampler
        client_description : natural-language client profile from GPT-4o/Claude

        Returns
        -------
        (system_prompt, user_prompt) strings ready for the LLM training loop.
        """
        from finplanenv.parser import (
            SYSTEM_PROMPT,
            PORTFOLIO_USER_TEMPLATE,
            RETIREMENT_USER_TEMPLATE,
            LOAN_USER_TEMPLATE,
        )

        if task == "portfolio":
            params = MARKET_PARAMS["portfolio"]
            asset_descriptions = "\n".join([
                f"  {i+1}. {params['tickers'][i]} | Sector: {params['sectors'][i]} | "
                f"ESG: {params['esg_ratings'][i]:.0f}/100"
                for i in range(self.config.n_assets_portfolio)
            ])
            user = PORTFOLIO_USER_TEMPLATE.format(
                client_profile    = client_description,
                n_assets          = self.config.n_assets_portfolio,
                asset_descriptions= asset_descriptions,
                max_drawdown_pct  = abs(metadata["max_drawdown_limit"]) * 100,
                banned_sectors    = metadata["banned_sectors"] or "none",
                hhi_limit         = metadata["hhi_limit"],
            )

        elif task == "retirement":
            params = MARKET_PARAMS["retirement"]
            h = metadata["narrative_hints"]
            asset_descriptions = (
                "  1. Equities (stocks): expected return 8%/yr, higher risk\n"
                "  2. Bonds (fixed income): expected return 4%/yr, lower risk"
            )
            user = RETIREMENT_USER_TEMPLATE.format(
                client_profile        = client_description,
                initial_balance       = h["initial_balance"],
                current_age           = h["current_age"],
                target_age            = h["target_age"],
                income_floor_monthly  = metadata["income_floor"],
                n_assets              = self.config.n_asset_classes_ret,
                asset_descriptions    = asset_descriptions,
                survival_pct          = int(metadata["mc_threshold"] * 100),
            )

        elif task == "loan":
            h = metadata["narrative_hints"]
            user = LOAN_USER_TEMPLATE.format(
                client_profile        = client_description,
                property_value        = h["property_value"],
                gross_monthly_income  = h["annual_income"] / 12,
                regulatory_tier       = h["regulatory_tier"],
            )

        else:
            raise ValueError(f"Unknown task: {task!r}")

        return SYSTEM_PROMPT, user

    def save_metadata(
        self,
        instances: list[dict],
        path:      str | Path,
    ) -> None:
        """
        Save instance metadata to JSONL (one JSON object per line).
        Numpy arrays are not included — re-created by ScenarioSampler
        during training using the instance_id index.
        """
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)

        def _json_safe(obj):
            if isinstance(obj, (np.integer,)): return int(obj)
            if isinstance(obj, (np.floating,)): return float(obj)
            if isinstance(obj, np.ndarray): return obj.tolist()
            if isinstance(obj, set): return list(obj)
            return obj

        with open(path, "w") as f:
            for inst in instances:
                f.write(json.dumps(inst, default=_json_safe) + "\n")

    def load_metadata(self, path: str | Path) -> list[dict]:
        """Load instance metadata from JSONL."""
        with open(path) as f:
            return [json.loads(line) for line in f if line.strip()]


